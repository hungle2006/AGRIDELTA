import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {BEAN_DROP_MS,BEAN_DIVIDER_COUNT,beanDropPose,beanDropPosition} from '../bean-drop-state.js';
const get=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
test('The same bean falls straight down to the end of the entire Start page in 2s',()=>{
  assert.equal(BEAN_DROP_MS,2000);
  assert.equal(BEAN_DIVIDER_COUNT,4);
  assert.equal(beanDropPose(0).visible,true);
  assert.ok(beanDropPose(240).opacity>.95);
  assert.equal(beanDropPose(1100).x,0);
  assert.ok(beanDropPose(1800).progress>.5);
  assert.ok(beanDropPosition(1600,400,8000)>400);
  assert.equal(beanDropPosition(2000,400,8000),8000);
  assert.ok(beanDropPosition(1500,400,8000)>beanDropPosition(700,400,8000));
  assert.equal(beanDropPose(2000).opacity,0);
  assert.equal(beanDropPose(2000).visible,false);
  assert.equal(beanDropPose(3500).visible,false);
});
test('Full-page rice-field background and a single shared overlay replace per-divider pictures',()=>{
  const root=get('root-guide.js'),css=get('bean-divider.css');
  assert.match(root,/class="site-field-backdrop"/);
  assert.match(root,/class="bean-fall-overlay" id="bean-fall-overlay"/);
  assert.match(root,/initBeanTransitions\(site, find\('#bean-fall-overlay'\)\)/);
  assert.doesNotMatch(root,/class="bean-pod-target"/);
  for(const id of ['01','02','03','04'])assert.ok(root.includes("beanDivider('"+id+"'"),id);
  assert.match(root,/id="live-earth"/);
  assert.match(css,/\.site-field-backdrop/);
  assert.match(css,/start-landscape-clear\.webp/);
  assert.match(css,/filter:blur\(11px\)/);
  assert.match(css,/\.bean-fall-overlay/);
  assert.match(css,/pointer-events:none/);
  assert.doesNotMatch(css,/--rice-photo/);
  assert.doesNotMatch(css,/\.bean-pod-target/);
});
test('Real Blender fruit uses one shared WebGL renderer and full site coordinates',()=>{
  const js=get('bean-drop-scene.js');
  assert.match(js,/start-lifecycle-live\.glb/);
  assert.match(js,/fruit\.\*bean\.\*pod/i);
  assert.match(js,/site\.scrollHeight-38/);
  assert.match(js,/site\.getBoundingClientRect\(\)/);
  assert.match(js,/line\.getBoundingClientRect\(\)/);
  assert.match(js,/beanDropPosition\(elapsed,startY,endY\)/);
  assert.match(js,/renderer\.render\(scene,camera\)/);
  assert.match(js,/IntersectionObserver/);
  assert.match(js,/reduce\.matches/);
  assert.doesNotMatch(js,/\.gif/);
});

test('Section dividers render only a hairline, with no spacer block or decorative dots',()=>{
  const css=get('bean-divider.css');
  assert.match(css,/\.earth-site \.bean-transition,\s*\.earth-site \.bean-transition--hero/);
  assert.match(css,/height:1px;\s*min-height:1px;\s*max-height:1px/);
  assert.match(css,/\.earth-site \.bean-transition-line\s*\{[\s\S]*?top:0;[\s\S]*?height:1px;/);
  assert.match(css,/background:linear-gradient\(90deg,transparent/);
  assert.match(css,/\.earth-site \.bean-transition-line::before,\s*\.earth-site \.bean-transition-line::after\{content:none\}/);
  assert.doesNotMatch(css,/\.bean-transition\s*\{[^}]*min-height:clamp/);
  const js=get('bean-drop-scene.js');
  assert.match(js,/divider\.querySelector\('\.bean-transition-line'\)/);
  assert.match(js,/startY=lineRect\.top/);
});
